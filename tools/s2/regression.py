"""S2 regression: DFG -> MCTS placement -> netlist route -> cin -> RTL, judged by
the steady-state value of every captured output channel.
Criterion: for each output array, the trailing run of identical non-zero captured
values must be >= 8 samples long and equal the DFG's expected result. Trailing
zeros are skipped first, so a case that stops capturing early (dfg_big prints 64
samples then 64 zeros) still reports the last real value and its run length.

Cases (8): chain_dfg / dfg_chain5 / dfg_branch / dfg_const / dfg_mixed /
dfg_scale / dfg_multi (two output channels) / dfg_big (10 compute PEs, 6 IOB
const streams, multi-GIB routing - the case that motivated the occ + route_parity
fixes, expected steady value 31).

Cases run serially: run_dfg.sh rewrites main_s2.c and the tag-prefixed artefacts
in place, so parallel jobs would clobber each other. Use --only to iterate on a
single case, or run separate cases in separate working copies.

usage: python regression.py [--only SUBSTR] [--repeat N]
  --only SUBSTR  仅跑文件名含 SUBSTR 的用例（无匹配时退出码 2，不静默通过）
  --repeat N     每个用例重复 N 次（抽检布线的随机性）
"""
import re, os, subprocess, sys, time

S2 = os.path.dirname(os.path.abspath(__file__))
CASES = [
    ('chain_dfg.json', [6]),      # 3-5=-2 -> +3=1  -> +5=6
    ('dfg_chain5.json', [9]),     # -2 -> 1 -> 6 -> +3 = 9
    ('dfg_branch.json', [3]),     # SUB fanout: -2+5 = 3
    ('dfg_const.json', [8]),      # CONST inline on PE: 3+5 = 8, no IOB stream
    ('dfg_mixed.json', [13]),     # stream 3 + CONST 5 = 8 -> +5 = 13
    ('dfg_scale.json', [11]),     # 5 ops, double fanout, 3 inline consts
    ('dfg_multi.json', [8, -2]),  # two output channels in one run
    # A=3,B=5: t1=A+B=8 t2=A+7=10 t3=B+7=12 t4=A+B=8 -> s1=18 s2=20 -> u=38
    # -> v=u-7=31. First case with 10 compute PEs and 6 IOB const streams
    # (2 input streams + 1 const fanout), i.e. the multi-GIB routing stress case.
    ('dfg_big.json', [31]),
    # Generated by gen_dag.py (--shape chain --layers 12 --width 1 --outputs 2
    # --consts 3): a 12-stage pipeline where stage i takes stage i-1 as operand
    # 0 and stage i-2 as operand 1, fanout 2 throughout. Expected values come
    # from gen_dag.evaluate(), which is written independently of mcts_bridge
    # (see dfg_dag_chain12o2c3_expect.json). Two capture channels on one run.
    ('dfg_dag_chain12o2c3.json', [4, 6]),
]

def steady(run_log):
    """{out_index: (steady_value, trailing_run_length)}"""
    t = open(run_log).read()
    arrays = {}
    for k, i, v in re.findall(r'O(\d+)\[(\d+)\] = (-?\d+)', t):
        arrays.setdefault(int(k), []).append(int(v))
    res = {}
    for k, v in arrays.items():
        i = len(v) - 1
        while i >= 0 and v[i] == 0:
            i -= 1
        if i < 0:
            res[k] = (None, 0)
            continue
        val, run = v[i], 0
        while i >= 0 and v[i] == val:
            run += 1
            i -= 1
        res[k] = (val, run)
    return res

REMAP_BUDGET = 12   # mcts_bridge.py retries the whole mapping this many times

def bridge_hint(tag):
    """Why a case failed, read from the bridge log.

    run_dfg.sh pipes mcts_bridge.py through `tee`, so routing asserts land in
    tag_bridge.log and never reach stderr; without this the FAIL line is empty.
    """
    path = os.path.join(S2, tag + '_bridge.log')
    if not os.path.exists(path):
        return 'bridge log missing (%s)' % os.path.basename(path)
    lines = [l.strip() for l in open(path, errors='replace')]
    why = [l[len('emission failed, retrying: '):] for l in lines
           if l.startswith('emission failed, retrying: ')]
    if why:
        if len(why) >= REMAP_BUDGET:
            return 'remap budget exhausted (%d/%d): %s' % (len(why), REMAP_BUDGET, why[-1])
        return 'last attempt: %s (%d remap failure(s))' % (why[-1], len(why))
    tail = next((l for l in reversed(lines) if l), '')
    if 'Error' in tail or 'error' in tail:
        return tail[-160:]
    return 'no routing error in bridge log; check %s' % os.path.basename(path)

def opt(args, name, default=None):
    """value of `--name VALUE`; exits loudly instead of IndexError when it is last"""
    if name not in args:
        return default
    i = args.index(name)
    if i + 1 >= len(args):
        raise SystemExit('%s needs a value' % name)
    return args[i + 1]

def main():
    args = sys.argv[1:]
    rep = int(opt(args, '--repeat', 1))
    only = opt(args, '--only')
    cases = [c for c in CASES if only is None or only in c[0]]
    if not cases:
        print('no case matches --only %r; known cases: %s'
              % (only, ', '.join(d for d, _ in CASES)))
        return 2
    ok = total = 0
    t0 = time.time()
    for dfg, expect in cases:
        for k in range(rep):
            tag = 'rg_%s_%d' % (os.path.splitext(dfg)[0], k)
            total += 1
            p = subprocess.run([os.path.join(S2, 'run_dfg.sh'), dfg, tag],
                               capture_output=True, text=True, cwd=S2)
            if p.returncode != 0:
                err = p.stderr.strip()[-120:] or p.stdout.strip()[-120:]
                print('%-22s FAIL (bridge/compile)  %s' % (tag, err))
                print('%-22s   -> %s' % ('', bridge_hint(tag)))
                continue
            st = steady(os.path.join(S2, tag + '_run.log'))
            got = [st.get(i, (None, 0)) for i in range(len(expect))]
            good = all(v == e and run >= 8 for (v, run), e in zip(got, expect))
            ok += good
            print('%-22s got=%-20s expect=%-10s %s'
                  % (tag, [v for v, _ in got], expect, 'PASS' if good else 'FAIL'))
            if not good:
                print('%-22s   runs=%s (need >=8)  -> %s'
                      % ('', [r for _, r in got], bridge_hint(tag)))
    print('\n%d/%d PASS' % (ok, total))
    print('elapsed %.1fs' % (time.time() - t0))
    return 0 if ok == total else 1

if __name__ == '__main__':
    sys.exit(main())
