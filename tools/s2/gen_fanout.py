"""Fan-out kernel: one input multiplied by k constants and summed.

Why this exists: the dense layers generated by `gen_nn.py` do one multiply per
activation and top out near 2-4 ops/cycle, while conv2d (nine taps per output)
reaches ~19. ops/cycle therefore looks like it scales with **arithmetic intensity
per input**, not with batch size. This generator makes that testable without the
LLVM front end: the same single input stream feeds k multipliers, so the work per
sample grows while the input traffic stays one stream (plus the constants).

    y = x * (c1 + c2 + ... + ck)      evaluated as sum_i (x * ci)

per sample: k multiplies and k-1 adds = 2k-1 ops.

usage: python gen_fanout.py --k 4 --name fan4
"""
import argparse
import json
import os

IO_FIELDS = {'pattern': '4, 91', 'size': '256', 'offset': '0, 0'}
X_VALUE = 3          # mcts_bridge fixes %const1 at 3


def build(k):
    objs, edges = [], []

    def node(**kw):
        kw['_gvid'] = len(objs)
        objs.append(kw)
        return kw['_gvid']

    def edge(t, h, o):
        edges.append({'_gvid': len(edges), 'tail': t, 'head': h, 'operand': o})

    x = node(opcode='INPUT', name='CONST1', ref_name='%const1', **IO_FIELDS)
    muls = []
    for i in range(k):
        c = node(opcode='CONST', name='%%c%d' % (i + 1), value=str(i + 1))
        m = node(opcode='MUL', name='M%d' % i)
        edge(x, m, 0)
        edge(c, m, 1)
        muls.append(m)
    acc = muls[0]
    for m in muls[1:]:
        s = node(opcode='ADD', name='S%d' % len(objs))
        edge(acc, s, 0)
        edge(m, s, 1)
        acc = s
    out = node(opcode='OUTPUT', name='OUT', ref_name='%out0', **IO_FIELDS)
    edge(acc, out, 0)
    return {'name': 'fan%d' % k, 'directed': True,
            'objects': objs, 'edges': edges}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--k', type=int, default=4)
    ap.add_argument('--name', default=None)
    args = ap.parse_args()
    if args.k < 1:
        raise SystemExit('k must be >= 1')
    dfg = build(args.k)
    name = args.name or dfg['name']
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        'dfg_%s.json' % name)
    json.dump(dfg, open(path, 'w'), indent=1)
    expect = X_VALUE * sum(range(1, args.k + 1))
    json.dump({'name': name, 'expect': [expect],
               'ops_per_sample': 2 * args.k - 1,
               'compute_nodes': 2 * args.k - 1,
               'note': 'y = x * sum(1..k) with x = %d' % X_VALUE},
              open(path.replace('.json', '_expect.json'), 'w'), indent=1)
    print('%s: %d nodes, %d compute, expect=%d'
          % (path, len(dfg['objects']), 2 * args.k - 1, expect))


if __name__ == '__main__':
    main()
